export const dictionaries: Record<Lang, Dictionary> = { en, fil, ceb };

export function isLang(value: unknown): value is Lang {
  return typeof value === "string" && (languages as readonly string[]).includes(value);
}

/** Fills {placeholders}; falls back to English, then to the key itself. */
export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>) {
  const template = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

